"""Convert evidence to monthly RANGE partitions — data-preserving (spec 01 §6).

evidence is the highest-volume, append-only, IRREPLACEABLE table (never dropped,
only tiered). So unlike timeline_event this conversion preserves data: rename the
existing table aside, create the partitioned parent + partitions (including a
DEFAULT partition so no historical row can fail to route), copy rows over, then
drop the old table. Retention is DETACH of cold months, never DROP.

Revision ID: 0004
Revises: 0003
"""

from collections.abc import Sequence
from datetime import UTC, datetime

from alembic import op

from maintenance import create_partition_sql, next_partitions

revision: str = "0004"
down_revision: str | None = "0003"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

_COLS = (
    "id, source_id, collector_id, raw_document_id, url, content_hash, "
    "claim_type, claim, snippet, confidence, observed_at"
)


def upgrade() -> None:
    op.execute("ALTER TABLE evidence RENAME TO evidence_old")
    op.execute("ALTER INDEX evidence_claim_idx RENAME TO evidence_claim_idx_old")
    op.execute("ALTER INDEX evidence_hash_idx RENAME TO evidence_hash_idx_old")
    op.execute(
        """
        CREATE TABLE evidence (
            id bigint GENERATED BY DEFAULT AS IDENTITY,
            source_id bigint NOT NULL,
            collector_id bigint NOT NULL,
            raw_document_id bigint,
            url text NOT NULL,
            content_hash bytea NOT NULL,
            claim_type text NOT NULL,
            claim jsonb NOT NULL DEFAULT '{}',
            snippet text,
            confidence real NOT NULL DEFAULT 0.5,
            observed_at timestamptz NOT NULL DEFAULT now(),
            CONSTRAINT ck_evidence_conf CHECK (confidence >= 0 AND confidence <= 1),
            PRIMARY KEY (id, observed_at)
        ) PARTITION BY RANGE (observed_at)
        """
    )
    # DEFAULT partition catches any row outside the explicit monthly range.
    op.execute("CREATE TABLE evidence_default PARTITION OF evidence DEFAULT")
    for parent, dt in next_partitions(now=datetime.now(UTC), ahead=3):
        if parent == "evidence":
            op.execute(create_partition_sql(parent, dt))
    op.execute("CREATE INDEX evidence_claim_idx ON evidence (claim_type, observed_at)")
    op.execute("CREATE INDEX evidence_hash_idx ON evidence (content_hash)")

    # Preserve existing evidence (routes into the right partitions / DEFAULT).
    op.execute(f"INSERT INTO evidence ({_COLS}) SELECT {_COLS} FROM evidence_old")
    # Keep the identity sequence ahead of copied ids.
    op.execute(
        "SELECT setval(pg_get_serial_sequence('evidence','id'), "
        "COALESCE((SELECT max(id) FROM evidence), 1))"
    )
    op.execute("DROP TABLE evidence_old")


